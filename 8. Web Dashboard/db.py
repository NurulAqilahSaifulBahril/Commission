def save_contest_rules(month: str, rules: dict[str, Any], teams: list[dict[str, Any]],
                       username: str, roster: list[dict[str, Any]] | None = None) -> None:
    """Replace one month's rule set. Other months are never touched, so fixing
    August cannot alter what July's awards were calculated from."""
    now = _now()
    rule_payload = {k: rules.get(k) for k in CONTEST_RULE_FIELDS}
    rule_payload["activity_bonus_enabled"] = 1 if rules.get("activity_bonus_enabled") else 0

    by_team = {str(t.get("team")): t for t in teams}
    team_payloads = []
    for name in CONTEST_TEAMS:
        src = by_team.get(name, {})
        payload = {k: src.get(k) for k in CONTEST_TEAM_FIELDS}
        payload["team"] = name
        team_payloads.append(payload)

    with _lock, _connect() as conn:
        before_rule = conn.execute(
            "SELECT * FROM contest_rules WHERE month = %s", (month,)
        ).fetchone()
        before_teams = conn.execute(
            "SELECT * FROM contest_team_month WHERE month = %s ORDER BY team", (month,)
        ).fetchall()
        before_roster = conn.execute(
            "SELECT * FROM contest_roster WHERE month = %s ORDER BY team, agent", (month,)
        ).fetchall()
        before = {
            "rules": {k: before_rule[k] for k in CONTEST_RULE_FIELDS} if before_rule else None,
            "teams": [{k: r[k] for k in CONTEST_TEAM_FIELDS} for r in before_teams],
            "roster": [{k: r[k] for k in CONTEST_ROSTER_FIELDS} for r in before_roster],
        }

        conn.execute("DELETE FROM contest_rules WHERE month = %s", (month,))
        conn.execute("DELETE FROM contest_team_month WHERE month = %s", (month,))
        conn.execute("DELETE FROM contest_roster WHERE month = %s", (month,))

        cols = ", ".join(CONTEST_RULE_FIELDS)
        marks = ", ".join("%s" for _ in CONTEST_RULE_FIELDS)
        conn.execute(
            f"""INSERT INTO contest_rules (month, {cols}, created_by, created_at, updated_by, updated_at)
                VALUES (%s, {marks}, %s, %s, %s, %s)""",
            [month] + [rule_payload.get(k) for k in CONTEST_RULE_FIELDS]
            + [username, now, username, now],
        )

        t_cols = ", ".join(CONTEST_TEAM_FIELDS)
        t_marks = ", ".join("%s" for _ in CONTEST_TEAM_FIELDS)
        for payload in team_payloads:
            conn.execute(
                f"""INSERT INTO contest_team_month (month, {t_cols}, created_by, created_at, updated_by, updated_at)
                    VALUES (%s, {t_marks}, %s, %s, %s, %s)""",
                [month] + [payload.get(k) for k in CONTEST_TEAM_FIELDS]
                + [username, now, username, now],
            )

        roster_payloads = []
        for entry in (roster or []):
            team = str(entry.get("team") or "").strip()
            agent = str(entry.get("agent") or "").strip()
            if not team or not agent:
                continue          # a half-filled row is dropped, not stored blank
            # One agent can close several cases, so the row carries a list of
            # amounts. Anything unparseable is dropped rather than stored as a
            # case that would silently match the wrong invoice.
            raw_prices = entry.get("sales_prices")
            if isinstance(raw_prices, str):
                try:
                    raw_prices = json.loads(raw_prices or "[]")
                except ValueError:
                    raw_prices = []
            prices = []
            for value in (raw_prices or []):
                cleaned = str(value).replace(",", "").strip()
                if not cleaned:
                    continue
                try:
                    float(cleaned)
                except ValueError:
                    continue
                prices.append(cleaned)
            prices_json = json.dumps(prices)

            roster_payloads.append({"team": team, "agent": agent, "sales_prices": prices_json})
            conn.execute(
                """INSERT INTO contest_roster (month, team, agent, sales_prices, created_by, created_at, updated_by, updated_at)
                    VALUES (%s, %s, %s, %s, %s, %s, %s, %s)""",
                (month, team, agent, prices_json, username, now, username, now),
            )

        after = {"rules": rule_payload, "teams": team_payloads, "roster": roster_payloads}
        if before != after:
            conn.execute(
                """INSERT INTO audit_log
                   (user_id, username, action, entity_type, entity_summary, before_json, after_json, created_at)
                   VALUES (NULL, %s, 'update', 'contest_rule', %s, %s, %s, %s)""",
                (username, f"Monthly Contest rules {month}",
                 json.dumps(before), json.dumps(after), now),
            )


