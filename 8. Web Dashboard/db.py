def get_ega_rules(year: str, agent_type: str = "internal") -> dict[str, Any]:
    agent_type = (agent_type or "internal").strip().lower()
    with _connect() as conn:
        row = conn.execute(
            "SELECT * FROM ega_rules WHERE year = %s AND agent_type = %s", (year, agent_type)
        ).fetchone()
        rows = conn.execute(
            "SELECT * FROM ega_month_thresholds WHERE year = %s AND agent_type = %s ORDER BY month",
            (year, agent_type),
        ).fetchall()
    rules = {k: row[k] for k in EGA_RULE_FIELDS} if row else _ega_defaults(agent_type)
    months = [{k: r[k] for k in EGA_MONTH_FIELDS} for r in rows] or [dict(m) for m in EGA_MONTH_DEFAULTS]
    return {"year": year, "agent_type": agent_type, "saved": bool(row),
            "rules": rules, "months": months}


def save_ega_rules(year, rules, months, username, agent_type: str = "internal"):
    """Replace one (year, agent type) rule set. Scoped by both keys so saving
    Outsource can never overwrite Internal's thresholds."""
    agent_type = (agent_type or "internal").strip().lower()
    now = _now()
    payload = {k: rules.get(k) for k in EGA_RULE_FIELDS}
    month_payloads = [{k: m.get(k) for k in EGA_MONTH_FIELDS} for m in (months or [])]
    with _lock, _connect() as conn:
        before_row = conn.execute(
            "SELECT * FROM ega_rules WHERE year = %s AND agent_type = %s", (year, agent_type)
        ).fetchone()
        before_months = conn.execute(
            "SELECT * FROM ega_month_thresholds WHERE year = %s AND agent_type = %s ORDER BY month",
            (year, agent_type),
        ).fetchall()
        before = {"rules": {k: before_row[k] for k in EGA_RULE_FIELDS} if before_row else None,
                  "months": [{k: r[k] for k in EGA_MONTH_FIELDS} for r in before_months]}

        conn.execute("DELETE FROM ega_rules WHERE year = %s AND agent_type = %s", (year, agent_type))
        conn.execute("DELETE FROM ega_month_thresholds WHERE year = %s AND agent_type = %s", (year, agent_type))

        cols = ", ".join(EGA_RULE_FIELDS)
        marks = ", ".join("%s" for _ in EGA_RULE_FIELDS)
        conn.execute(
            f"""INSERT INTO ega_rules (year, agent_type, {cols}, created_by, created_at, updated_by, updated_at)
                VALUES (%s, %s, {marks}, %s, %s, %s, %s)""",
            [year, agent_type] + [payload.get(k) for k in EGA_RULE_FIELDS] + [username, now, username, now],
        )
        m_cols = ", ".join(EGA_MONTH_FIELDS)
        m_marks = ", ".join("%s" for _ in EGA_MONTH_FIELDS)
        for m in month_payloads:
            conn.execute(
                f"""INSERT INTO ega_month_thresholds (year, agent_type, {m_cols}, created_by, created_at, updated_by, updated_at)
                    VALUES (%s, %s, {m_marks}, %s, %s, %s, %s)""",
                [year, agent_type] + [m.get(k) for k in EGA_MONTH_FIELDS] + [username, now, username, now],
            )

        after = {"rules": payload, "months": month_payloads}
        if before != after:
            conn.execute(
                """INSERT INTO audit_log
                   (user_id, username, action, entity_type, entity_summary, before_json, after_json, created_at)
                   VALUES (NULL, %s, 'update', 'ega_rule', %s, %s, %s, %s)""",
                (username, f"EGA/ESA award rules {year} ({agent_type})",
                 json.dumps(before), json.dumps(after), now),
            )


