def _save_period_rules(table, key_col, key, fields, rules, username,
                       child=None, entity="rule", summary=""):
    """Replace one period's rule set (and its child rows, if any). Other periods
    are never touched, so fixing one month cannot restate another."""
    now = _now()
    payload = {k: rules.get(k) for k in fields}
    with _lock, _connect() as conn:
        before_row = conn.execute(f"SELECT * FROM {table} WHERE {key_col} = %s", (key,)).fetchone()
        before = {"rules": {k: before_row[k] for k in fields} if before_row else None}

        conn.execute(f"DELETE FROM {table} WHERE {key_col} = %s", (key,))
        cols = ", ".join(fields)
        marks = ", ".join("%s" for _ in fields)
        conn.execute(
            f"""INSERT INTO {table} ({key_col}, {cols}, created_by, created_at, updated_by, updated_at)
                VALUES (%s, {marks}, %s, %s, %s, %s)""",
            [key] + [payload.get(k) for k in fields] + [username, now, username, now],
        )

        after = {"rules": payload}
        if child:
            child_table, child_fields, child_rows = child
            before_children = conn.execute(
                f"SELECT * FROM {child_table} WHERE {key_col} = %s ORDER BY id", (key,)
            ).fetchall()
            before["rows"] = [{k: r[k] for k in child_fields} for r in before_children]
            conn.execute(f"DELETE FROM {child_table} WHERE {key_col} = %s", (key,))
            c_cols = ", ".join(child_fields)
            c_marks = ", ".join("%s" for _ in child_fields)
            saved_children = []
            for r in child_rows:
                vals = {k: r.get(k) for k in child_fields}
                saved_children.append(vals)
                conn.execute(
                    f"""INSERT INTO {child_table} ({key_col}, {c_cols}, created_by, created_at, updated_by, updated_at)
                        VALUES (%s, {c_marks}, %s, %s, %s, %s)""",
                    [key] + [vals.get(k) for k in child_fields] + [username, now, username, now],
                )
            after["rows"] = saved_children

        if before != after:
            conn.execute(
                """INSERT INTO audit_log
                   (user_id, username, action, entity_type, entity_summary, before_json, after_json, created_at)
                   VALUES (NULL, %s, 'update', %s, %s, %s, %s, %s)""",
                (username, entity, f"{summary} {key}",
                 json.dumps(before), json.dumps(after), now),
            )


