# ── Users ─────────────────────────────────────────────────────────────────────

def get_user_by_username(username: str) -> dict[str, Any] | None:
    with _connect() as conn:
        return conn.execute(
            "SELECT * FROM users WHERE username = %s AND is_active = 1", (username,)
        ).fetchone()


def get_user_by_id(user_id: int) -> dict[str, Any] | None:
    with _connect() as conn:
        return conn.execute("SELECT * FROM users WHERE id = %s", (user_id,)).fetchone()


def list_users() -> list[dict[str, Any]]:
    with _connect() as conn:
        return conn.execute(
            "SELECT id, username, role, is_active, created_at FROM users ORDER BY created_at ASC"
        ).fetchall()


def create_user(username: str, password_hash: str, role: str) -> int:
    with _lock, _connect() as conn:
        cur = conn.execute(
            "INSERT INTO users (username, password_hash, role, is_active, created_at) VALUES (%s, %s, %s, 1, %s) RETURNING id",
            (username, password_hash, role, _now()),
        )
        return cur.fetchone()["id"]


def update_user(user_id: int, *, username: str | None = None, password_hash: str | None = None,
                 role: str | None = None, is_active: bool | None = None) -> None:
    fields = []
    values: list[Any] = []
    if username is not None:
        fields.append("username = %s")
        values.append(username)
    if password_hash is not None:
        fields.append("password_hash = %s")
        values.append(password_hash)
    if role is not None:
        fields.append("role = %s")
        values.append(role)
    if is_active is not None:
        fields.append("is_active = %s")
        values.append(1 if is_active else 0)
    if not fields:
        return
    values.append(user_id)
    with _lock, _connect() as conn:
        conn.execute(f"UPDATE users SET {', '.join(fields)} WHERE id = %s", values)


def deactivate_user(user_id: int) -> None:
    update_user(user_id, is_active=False)


# ── Special cases ────────────────────────────────────────────────────────────

def get_special_cases(year: str, month: str, agent_type: str) -> list[dict[str, Any]]:
    with _connect() as conn:
        rows = conn.execute(
            """SELECT id, data_json FROM special_cases
               WHERE year = %s AND month = %s AND agent_type = %s""",
            (year, month, agent_type),
        ).fetchall()
    result = []
    for row in rows:
        item = json.loads(row["data_json"])
        item["id"] = row["id"]
        item["year"] = year
        item["month"] = month
        item["agent_type"] = agent_type
        result.append(item)
    return result


def save_special_cases(year: str, month: str, agent_type: str, new_cases: list[dict[str, Any]], username: str) -> None:
    """Replace the special cases for one (year, month, agent_type) bucket, logging an
    audit entry for every row removed, changed, or added."""
    now = _now()
    with _lock, _connect() as conn:
        existing_rows = conn.execute(
            """SELECT id, data_json FROM special_cases
               WHERE year = %s AND month = %s AND agent_type = %s""",
            (year, month, agent_type),
        ).fetchall()
        existing_payloads = [json.loads(r["data_json"]) for r in existing_rows]

        conn.execute(
            "DELETE FROM special_cases WHERE year = %s AND month = %s AND agent_type = %s",
            (year, month, agent_type),
        )

        new_payloads = [{k: c.get(k) for k in SPECIAL_CASE_FIELDS} for c in new_cases]
        for payload in new_payloads:
            conn.execute(
                """INSERT INTO special_cases
                   (year, month, agent_type, data_json, created_by, created_at, updated_by, updated_at)
                   VALUES (%s, %s, %s, %s, %s, %s, %s, %s)""",
                (year, month, agent_type, json.dumps(payload), username, now, username, now),
            )

        if existing_payloads != new_payloads:
            summary = f"{agent_type} {month}/{year} special cases"
            conn.execute(
                """INSERT INTO audit_log
                   (user_id, username, action, entity_type, entity_summary, before_json, after_json, created_at)
                   VALUES (NULL, %s, 'update', 'special_case', %s, %s, %s, %s)""",
                (username, summary, json.dumps(existing_payloads), json.dumps(new_payloads), now),
            )


